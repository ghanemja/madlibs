#!/usr/bin/env python3
"""Have AI models fill in the Fun Libs stories, for the "Human or AI?" game.

Run this on your own computer, with your own API key. The key is only used here;
the website itself never needs or sees it.

    pip install anthropic          # and/or: pip install openai
    export ANTHROPIC_API_KEY=...   # or OPENAI_API_KEY=...

    # 3 fill-ins per story from a Claude model
    python3 tools/generate_ai_fills.py --provider anthropic --model claude-sonnet-5-5 --n 3

    # a few stories only, to try it out
    python3 tools/generate_ai_fills.py --model claude-haiku-5-5 --stories pizza,zombies

    # an OpenAI model
    python3 tools/generate_ai_fills.py --provider openai --model gpt-4o --n 3

    # just rebuild data/ai_fills.js from data/ai_fills.json
    python3 tools/generate_ai_fills.py --js-only

Each story is sent in its own request, so fill-ins are sampled independently.
Results are appended to data/ai_fills.json (the source of truth) and
data/ai_fills.js (what the site loads) is rebuilt.
"""
import argparse
import datetime
import json
import os
import re
import sys
import time

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FUNLIBS = os.path.join(ROOT, 'data', 'funlibs.js')
FILLS_JSON = os.path.join(ROOT, 'data', 'ai_fills.json')
FILLS_JS = os.path.join(ROOT, 'data', 'ai_fills.js')

PROMPT_VERSION = 'v1'
SYSTEM = (
    "You are playing Mad Libs. You will see a short story with numbered blanks, each with a hint "
    "like (noun) or (past tense verb). Fill in every blank to make the finished story as funny as "
    "possible, the way a human Mad Libs player would. Each answer should match its hint and be a "
    "single word or a very short phrase."
)


def load_funlibs():
    with open(FUNLIBS) as f:
        s = f.read()
    return json.loads(s[s.index('=') + 1:].rstrip().rstrip(';'))


def load_fills():
    if os.path.exists(FILLS_JSON):
        with open(FILLS_JSON) as f:
            return json.load(f)
    return {'fills': []}


def save(fills):
    with open(FILLS_JSON, 'w') as f:
        json.dump(fills, f, ensure_ascii=False, indent=1)
    with open(FILLS_JS, 'w') as f:
        f.write('// Generated by tools/generate_ai_fills.py from data/ai_fills.json. Do not edit by hand.\n')
        f.write('window.AI_FILLS = ')
        json.dump(fills, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')


def story_prompt(st):
    text = re.sub(r'\[([a-z ]+):b(\d+)\]', lambda m: '___(%s: %s)' % (m.group(2), m.group(1)), st['template'])
    return (
        f'Story: "{st["title"]}"\n\n{text}\n\n'
        f'There are {len(st["blanks"])} blanks. Reply with ONLY a JSON array of '
        f'{len(st["blanks"])} strings, one per blank, in order.'
    )


def parse(text, n):
    m = re.search(r'\[.*\]', text, re.S)
    if not m:
        raise ValueError('no JSON array in reply')
    words = json.loads(m.group(0))
    if not isinstance(words, list) or len(words) != n:
        raise ValueError('expected %d words, got %s' % (n, len(words) if isinstance(words, list) else type(words)))
    return [str(w).strip() for w in words]


def make_client(provider):
    if provider == 'anthropic':
        import anthropic
        client = anthropic.Anthropic()

        def ask(model, prompt, temperature):
            r = client.messages.create(model=model, max_tokens=600, temperature=temperature, system=SYSTEM,
                                       messages=[{'role': 'user', 'content': prompt}])
            return ''.join(b.text for b in r.content if getattr(b, 'type', '') == 'text')
        return ask
    if provider == 'openai':
        import openai
        client = openai.OpenAI()

        def ask(model, prompt, temperature):
            r = client.chat.completions.create(model=model, temperature=temperature,
                                               messages=[{'role': 'system', 'content': SYSTEM}, {'role': 'user', 'content': prompt}])
            return r.choices[0].message.content
        return ask
    sys.exit('unknown provider: ' + provider)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--provider', default='anthropic', choices=['anthropic', 'openai'])
    ap.add_argument('--model', default='claude-sonnet-5-5')
    ap.add_argument('--n', type=int, default=2, help='fill-ins per story')
    ap.add_argument('--temperature', type=float, default=1.0)
    ap.add_argument('--stories', help='comma-separated story ids (default: all 50)')
    ap.add_argument('--js-only', action='store_true', help='only rebuild data/ai_fills.js')
    args = ap.parse_args()

    fills = load_fills()
    if args.js_only:
        save(fills)
        print('rebuilt', FILLS_JS, 'with', len(fills['fills']), 'fill-ins')
        return

    data = load_funlibs()
    wanted = set(args.stories.split(',')) if args.stories else None
    ask = make_client(args.provider)
    source = '%s:%s' % (args.provider, args.model)
    added = 0
    for st in data['stories']:
        if wanted and st['id'] not in wanted:
            continue
        for i in range(args.n):
            for attempt in range(3):
                try:
                    words = parse(ask(args.model, story_prompt(st), args.temperature), len(st['blanks']))
                    break
                except Exception as e:  # noqa: BLE001 - retry on any API/parse problem
                    print('  retry %s #%d: %s' % (st['id'], i, e))
                    time.sleep(2 * (attempt + 1))
            else:
                print('  gave up on', st['id'])
                continue
            fills['fills'].append({
                'story': st['id'], 'source': source, 'model': args.model, 'method': 'api',
                'prompt_version': PROMPT_VERSION, 'temperature': args.temperature,
                'created': datetime.date.today().isoformat(), 'words': words,
            })
            added += 1
            print('%-45s %s' % (st['id'], ', '.join(words)))
        save(fills)  # save as we go
    print('added %d fill-ins from %s; total %d' % (added, source, len(fills['fills'])))


if __name__ == '__main__':
    main()
